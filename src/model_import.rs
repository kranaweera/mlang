//! Small, dependency-free model interchange format. Only dense f32 regression networks.
//! Files are data, never executable source.
struct Layer { input: usize, output: usize, activation: String, weights: Vec<f32>, biases: Vec<f32> }
fn values(line: &str, label: &str, expected: usize) -> Result<Vec<f32>, String> {
    let mut parts = line.split_whitespace();
    if parts.next() != Some(label) { return Err(format!("expected {label} line")); }
    let vals: Vec<f32> = parts.map(|s| s.parse::<f32>().map_err(|_| format!("invalid float in {label}"))).collect::<Result<_,_>>()?;
    if vals.len() != expected { return Err(format!("{label}: expected {expected} numbers, got {}", vals.len())); }
    if !vals.iter().all(|v| v.is_finite()) { return Err(format!("{label}: non-finite weight")); }
    Ok(vals)
}
fn literal(f: f32) -> String { format!("{f:.9}") }
fn vector(xs: &[f32]) -> String {
    format!("[{}]", xs.iter().map(|v| literal(*v)).collect::<Vec<_>>().join(", "))
}
fn matrix(xs: &[f32], cols: usize) -> String {
    format!("[{}]", xs.chunks(cols).map(vector).collect::<Vec<_>>().join(", "))
}
pub fn import(input: &str) -> Result<String, String> {
    let lines: Vec<&str> = input.lines().map(str::trim).filter(|s| !s.is_empty() && !s.starts_with('#')).collect();
    if lines.first().copied() != Some("MLANG-MODEL 1") { return Err("expected MLANG-MODEL 1 header".into()); }
    let mut i = 1;
    let get = |index: usize| -> Result<&str, String> { lines.get(index).copied().ok_or_else(|| "unexpected end of model".into()) };
    let input_line = get(i)?; i+=1;
    let mut tok = input_line.split_whitespace();
    if tok.next() != Some("input") { return Err("expected input N".into()); }
    let initial: usize = tok.next().ok_or("missing input count")?.parse().map_err(|_| "invalid input count")?;
    if tok.next().is_some() || initial==0 || initial>4096 {return Err("input must be in 1..4096".into());}
    let mut layers = Vec::new();
    let mut previous = initial;
    while i < lines.len() {
        if layers.len() >= 16 {return Err("maximum of 16 dense layers".into());}
        let mut parts = get(i)?.split_whitespace(); i+=1;
        if parts.next()!=Some("dense") { return Err("expected dense OUT relu|linear".into()); }
        let output:usize = parts.next().ok_or("missing layer width")?.parse().map_err(|_| "invalid layer width")?;
        let activation=parts.next().ok_or("missing activation")?.to_owned();
        if parts.next().is_some() || output==0 || output>4096 || !["relu","linear"].contains(&activation.as_str()) {
            return Err("dense requires width 1..4096 and activation relu|linear".into());
        }
        let count=output.checked_mul(previous).ok_or("layer too large")?;
        if count>4096 { return Err("weight matrices are limited to 4096 elements".into()); }
        let weights=values(get(i)?,"weights",count)?;i+=1;
        let biases=values(get(i)?,"bias",output)?;i+=1;
        layers.push(Layer {input:previous,output,activation,weights,biases});
        previous=output;
    }
    if layers.is_empty() { return Err("model needs at least one dense layer".into()); }
    let mut code=String::from("// Generated by MLang model importer. Embedded f32 weights.\n");
    code.push_str(&format!("fn predict(x: f32[{initial}]) -> f32[{previous}] {{\n"));
    let mut current="x".to_string();
    for (idx,layer) in layers.iter().enumerate() {
        let n=idx+1;
        code.push_str(&format!("    let w{n} = {};\n",matrix(&layer.weights,layer.input)));
        code.push_str(&format!("    let b{n} = {};\n",vector(&layer.biases)));
        let formula=format!("w{n} @ {current} + b{n}");
        code.push_str(&format!("    let h{n} = {};\n",if layer.activation=="relu" {format!("relu({formula})")} else {formula}));
        current=format!("h{n}");
    }
    code.push_str(&format!("    return {current};\n}}\n"));
    let sample=vec![0.0f32;initial];
    code.push_str(&format!("fn main() {{ print(predict({})); }}\n",vector(&sample)));
    Ok(code)
}
#[cfg(test)]
mod tests {
    use super::*;
    const GOOD:&str="MLANG-MODEL 1\ninput 2\ndense 3 relu\nweights 1 0 0 2 -1 1\nbias 0 0 1\ndense 1 linear\nweights 0.5 0.25 1\nbias 0.5\n";
    #[test] fn imports_dense() { let code=import(GOOD).unwrap(); assert!(code.contains("fn predict(x: f32[2]) -> f32[1]")); assert!(crate::compile(&code).is_ok()); }
    #[test] fn rejects_bad_counts() {assert!(import("MLANG-MODEL 1\ninput 2\ndense 1 linear\nweights 1\nbias 0").is_err());}
    #[test] fn rejects_nan() {assert!(import("MLANG-MODEL 1\ninput 1\ndense 1 linear\nweights NaN\nbias 0").is_err());}
    #[test] fn rejects_unknown_activation() {assert!(import("MLANG-MODEL 1\ninput 1\ndense 1 tanh\nweights 1\nbias 0").is_err());}
}
