use crate::ast::{Expr, Program, Stmt, Type};
use crate::semantic::infer;
use std::collections::{BTreeSet, HashMap};

fn type_c(ty: &Type) -> String {
    match ty { Type::F32 => "float".into(), Type::Vector(n) => format!("ml_vec_{n}"), Type::Matrix(r, c) => format!("ml_mat_{r}_{c}") }
}
fn expression(expr: &Expr, vars: &HashMap<String, Type>, sigs: &HashMap<String, (Vec<Type>, Option<Type>)>) -> String {
    match expr {
        Expr::Number(n) => format!("{n:.9}f"),
        Expr::Var(name) => format!("ml_{name}"),
        Expr::Vector(items) => format!("(ml_vec_{}){{{{{}}}}}", items.len(), items.iter().map(|x| expression(x, vars, sigs)).collect::<Vec<_>>().join(", ")),
        Expr::UnaryMinus(x) => format!("(-{})", expression(x, vars, sigs)),
        Expr::Binary(a, op, b) => format!("({} {op} {})", expression(a, vars, sigs), expression(b, vars, sigs)),
        Expr::Call(name, args) => {
            let args_s = args.iter().map(|x| expression(x, vars, sigs)).collect::<Vec<_>>().join(", ");
            if name == "dot" {
                let ty = infer(&args[0], vars, sigs).expect("validated AST");
                let Type::Vector(n) = ty else { unreachable!() };
                format!("ml_dot_{n}({args_s})")
            } else { format!("ml_{name}({args_s})") }
        }
    }
}
fn collect_vectors(expr: &Expr, sizes: &mut BTreeSet<usize>) {
    match expr {
        Expr::Vector(xs) => { sizes.insert(xs.len()); for x in xs { collect_vectors(x, sizes); } }
        Expr::UnaryMinus(x) => collect_vectors(x, sizes),
        Expr::Binary(a, _, b) => { collect_vectors(a, sizes); collect_vectors(b, sizes); }
        Expr::Call(_, xs) => for x in xs { collect_vectors(x, sizes); },
        _ => {}
    }
}

pub fn emit_c(program: &Program) -> String {
    let mut sizes = BTreeSet::new();
    for f in &program.functions {
        for (_, ty) in &f.params { if let Type::Vector(n) = ty { sizes.insert(*n); } }
        if let Some(Type::Vector(n)) = &f.result { sizes.insert(*n); }
        for s in &f.body { match s { Stmt::Let(_, e) | Stmt::Return(e) | Stmt::Expr(e) => collect_vectors(e, &mut sizes) } }
    }
    let sigs: HashMap<_, _> = program.functions.iter().map(|f| (f.name.clone(), (f.params.iter().map(|(_, ty)| ty.clone()).collect(), f.result.clone()))).collect();
    let mut out = String::from("/* Generated by MLang v0.1. Do not edit. */\n#include <stdio.h>\n\n");
    for n in &sizes {
        out.push_str(&format!("typedef struct {{ float data[{n}]; }} ml_vec_{n};\n"));
        out.push_str(&format!("static float ml_dot_{n}(ml_vec_{n} a, ml_vec_{n} b) {{\n  float sum = 0.0f;\n  for (size_t i = 0; i < {n}; ++i) sum += a.data[i] * b.data[i];\n  return sum;\n}}\n"));
    }
    out.push('\n');
    for f in &program.functions {
        if f.name == "main" { continue; }
        let params = f.params.iter().map(|(name, ty)| format!("{} ml_{name}", type_c(ty))).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("{} ml_{}({});\n", f.result.as_ref().map(type_c).unwrap_or("void".into()), f.name, if params.is_empty() { "void" } else { &params }));
    }
    out.push('\n');
    for f in &program.functions {
        let main = f.name == "main";
        let name = if main { "main".to_string() } else { format!("ml_{}", f.name) };
        let ret = if main { "int".to_string() } else { f.result.as_ref().map(type_c).unwrap_or("void".into()) };
        let params = f.params.iter().map(|(n, t)| format!("{} ml_{n}", type_c(t))).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("{ret} {name}({}) {{\n", if params.is_empty() { "void" } else { &params }));
        let mut vars: HashMap<String, Type> = f.params.iter().cloned().collect();
        for stmt in &f.body {
            match stmt {
                Stmt::Let(n, e) => {
                    let ty = infer(e, &vars, &sigs).expect("validated AST");
                    out.push_str(&format!("  {} ml_{n} = {};\n", type_c(&ty), expression(e, &vars, &sigs)));
                    vars.insert(n.clone(), ty);
                }
                Stmt::Return(e) => out.push_str(&format!("  return {};\n", expression(e, &vars, &sigs))),
                Stmt::Expr(Expr::Call(n, args)) if n == "print" => out.push_str(&format!("  printf(\"%.9g\\n\", (double)({}));\n", expression(&args[0], &vars, &sigs))),
                Stmt::Expr(e) => out.push_str(&format!("  (void)({});\n", expression(e, &vars, &sigs))),
            }
        }
        if main { out.push_str("  return 0;\n"); }
        out.push_str("}\n\n");
    }
    out
}
